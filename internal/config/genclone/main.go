// genclone emits internal/config/settings_clone.go: a generated deep copy of Settings
// that does `c := *s` then explicit deep copies of every map, slice, pointer and nested
// value that holds references. The reflection clone (settings.go cloneSettings) stays ONLY
// in the test as the oracle. Stdlib-only (go/parser + go/ast, no go/types, no x/tools).
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"sort"
	"strconv"
	"strings"
)

var fset = token.NewFileSet()

func main() {
	typeSpecs := map[string]ast.Expr{}
	var settings *ast.StructType
	entries, err := os.ReadDir(".")
	if err != nil {
		panic(err)
	}
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") ||
			strings.HasSuffix(name, "_test.go") || name == "settings_clone.go" {
			continue
		}
		pf, err := parser.ParseFile(fset, name, nil, 0)
		if err != nil {
			panic(err)
		}
		for _, decl := range pf.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				typeSpecs[ts.Name.Name] = ts.Type
				if ts.Name.Name == "Settings" {
					settings = ts.Type.(*ast.StructType)
				}
			}
		}
	}
	if settings == nil {
		panic("Settings not found")
	}

	g := &gen{typeSpecs: typeSpecs, helpers: map[string]*helper{}, eqHelpers: map[string]*helper{}}
	var buf bytes.Buffer

	buf.WriteString("// Code generated by genclone; DO NOT EDIT.\n")
	buf.WriteString("// settings_clone.go holds the generated deep copy of Settings: `c := *s` then\n")
	buf.WriteString("// explicit deep copies of every map, slice, pointer and nested value that holds\n")
	buf.WriteString("// references.\n\n")
	buf.WriteString("package config\n\n")

	buf.WriteString("// Clone returns a deep copy of s. Mutating the returned Settings (including its\n")
	buf.WriteString("// maps, slices and pointed-to values) never touches s.\n")
	buf.WriteString("func (s *Settings) Clone() *Settings {\n")
	buf.WriteString("\tif s == nil {\n\t\treturn nil\n\t}\n")
	buf.WriteString("\tc := *s\n")
	structFields(settings, func(name string, typ ast.Expr) {
		g.emitCopy(&buf, "\t", typ, "s."+name, "c."+name)
	})
	buf.WriteString("\treturn &c\n}\n")

	buf.WriteString("\n// equal reports whether s and o hold identical values (deep, all fields, including\n")
	buf.WriteString("// every map, slice, pointer and nested value). It replaces the reflection\n")
	buf.WriteString("// changedFieldNames/valueChanged diff in Update.\n")
	buf.WriteString("func (s *Settings) equal(o *Settings) bool {\n")
	buf.WriteString("\tif s == o {\n\t\treturn true\n\t}\n")
	buf.WriteString("\tif s == nil || o == nil {\n\t\treturn false\n\t}\n")
	structFields(settings, func(name string, typ ast.Expr) {
		g.emitEqual(&buf, "\t", typ, "s."+name, "o."+name)
	})
	buf.WriteString("\treturn true\n}\n")

	var names []string
	for n := range g.helpers {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		g.helpers[n].emit(&buf)
	}
	var eqNames []string
	for n := range g.eqHelpers {
		eqNames = append(eqNames, n)
	}
	sort.Strings(eqNames)
	for _, n := range eqNames {
		g.eqHelpers[n].emitEq(&buf)
	}

	out, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, buf.String())
		panic(err)
	}
	if err := os.WriteFile("settings_clone.go", out, 0o644); err != nil {
		panic(err)
	}
	fmt.Println("wrote internal/config/settings_clone.go")
}

// structFields yields each exported field name and type of a struct (embedded fields
// use the embedded type's base name).
func structFields(st *ast.StructType, yield func(name string, typ ast.Expr)) {
	for _, f := range st.Fields.List {
		if len(f.Names) == 0 {
			if n := embeddedName(f.Type); n != "" && ast.IsExported(n) {
				yield(n, f.Type)
			}
			continue
		}
		for _, n := range f.Names {
			if ast.IsExported(n.Name) {
				yield(n.Name, f.Type)
			}
		}
	}
}

func embeddedName(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return embeddedName(t.X)
	case *ast.SelectorExpr:
		return t.Sel.Name
	}
	return ""
}

// typeString prints an AST type expression back to Go source.
func typeString(e ast.Expr) string {
	var b bytes.Buffer
	printer.Fprint(&b, fset, e)
	return b.String()
}

type helper struct {
	name  string
	typ   string
	strct *ast.StructType
	g     *gen
}

type gen struct {
	typeSpecs map[string]ast.Expr
	helpers   map[string]*helper
	eqHelpers map[string]*helper
	n         int
}

func (g *gen) loopVar(prefix string) string {
	g.n++
	return fmt.Sprintf("%s%d", prefix, g.n)
}

// deref resolves a package-local named type to its underlying expression, unwrapping
// aliases; builtins and foreign selector types are returned as-is.
func (g *gen) deref(e ast.Expr) ast.Expr {
	for {
		id, ok := e.(*ast.Ident)
		if !ok {
			return e
		}
		r, ok := g.typeSpecs[id.Name]
		if !ok {
			return id
		}
		e = r
	}
}

// holdsRefs reports whether e holds a reference (map/slice/pointer, direct or nested).
// Package-local named types resolve by name; foreign (selector) types are opaque scalars.
func (g *gen) holdsRefs(e ast.Expr) bool {
	switch t := g.deref(e).(type) {
	case *ast.Ident, *ast.SelectorExpr:
		return false
	case *ast.StarExpr, *ast.MapType:
		return true
	case *ast.ArrayType:
		if t.Len == nil {
			return true
		}
		return g.holdsRefs(t.Elt)
	case *ast.StructType:
		for _, f := range t.Fields.List {
			if fieldExported(f) && g.holdsRefs(f.Type) {
				return true
			}
		}
		return false
	}
	return false
}

func fieldExported(f *ast.Field) bool {
	if len(f.Names) == 0 {
		return ast.IsExported(embeddedName(f.Type))
	}
	for _, n := range f.Names {
		if ast.IsExported(n.Name) {
			return true
		}
	}
	return false
}

func structName(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return structName(t.X)
	}
	return ""
}

// emitCopy writes statements that copy src into dst, recursing for nested refs and
// collecting struct-with-references types into g.helpers.
func (g *gen) emitCopy(buf *bytes.Buffer, indent string, t ast.Expr, src, dst string) {
	switch u := g.deref(t).(type) {
	case *ast.Ident, *ast.SelectorExpr:
		// scalar or opaque foreign value: covered by the outer struct copy
	case *ast.ArrayType:
		if u.Len == nil {
			elem := u.Elt
			if !g.holdsRefs(elem) {
				fmt.Fprintf(buf, "%sif %s != nil {\n", indent, src)
				fmt.Fprintf(buf, "%s\t%s = make(%s, len(%s))\n", indent, dst, typeString(t), src)
				fmt.Fprintf(buf, "%s\tcopy(%s, %s)\n", indent, dst, src)
				fmt.Fprintf(buf, "%s} else {\n", indent)
				fmt.Fprintf(buf, "%s\t%s = nil\n", indent, dst)
				fmt.Fprintf(buf, "%s}\n", indent)
			} else {
				i := g.loopVar("i")
				fmt.Fprintf(buf, "%sif %s != nil {\n", indent, src)
				fmt.Fprintf(buf, "%s\t%s = make(%s, len(%s))\n", indent, dst, typeString(t), src)
				fmt.Fprintf(buf, "%s\tfor %s := range %s {\n", indent, i, src)
				g.emitCopy(buf, indent+"\t\t", elem, src+"["+i+"]", dst+"["+i+"]")
				fmt.Fprintf(buf, "%s\t}\n", indent)
				fmt.Fprintf(buf, "%s} else {\n", indent)
				fmt.Fprintf(buf, "%s\t%s = nil\n", indent, dst)
				fmt.Fprintf(buf, "%s}\n", indent)
			}
		} else if g.holdsRefs(u.Elt) {
			panic("array element holds references: " + typeString(t))
		}
	case *ast.StructType:
		if !g.holdsRefs(u) {
			return // struct of scalars is a value copy
		}
		name := "snapClone" + structName(t)
		if _, ok := g.helpers[name]; !ok {
			g.helpers[name] = &helper{name: name, typ: structName(t), strct: u, g: g}
		}
		fmt.Fprintf(buf, "%s%s = %s(%s)\n", indent, dst, name, src)
	case *ast.MapType:
		val := u.Value
		k, v := g.loopVar("k"), g.loopVar("v")
		fmt.Fprintf(buf, "%sif %s != nil {\n", indent, src)
		fmt.Fprintf(buf, "%s\t%s = make(%s, len(%s))\n", indent, dst, typeString(t), src)
		fmt.Fprintf(buf, "%s\tfor %s, %s := range %s {\n", indent, k, v, src)
		if !g.holdsRefs(val) {
			fmt.Fprintf(buf, "%s\t\t%s[%s] = %s\n", indent, dst, k, v)
		} else {
			g.emitCopy(buf, indent+"\t\t", val, v, dst+"["+k+"]")
		}
		fmt.Fprintf(buf, "%s\t}\n", indent)
		fmt.Fprintf(buf, "%s} else {\n", indent)
		fmt.Fprintf(buf, "%s\t%s = nil\n", indent, dst)
		fmt.Fprintf(buf, "%s}\n", indent)
	case *ast.StarExpr:
		elem := u.X
		fmt.Fprintf(buf, "%sif %s != nil {\n", indent, src)
		if !g.holdsRefs(elem) {
			fmt.Fprintf(buf, "%s\tv := *%s\n%s\t%s = &v\n", indent, src, indent, dst)
		} else {
			fmt.Fprintf(buf, "%s\tvar v %s\n", indent, typeString(elem))
			g.emitCopy(buf, indent+"\t", elem, "*"+src, "v")
			fmt.Fprintf(buf, "%s\t%s = &v\n", indent, dst)
		}
		fmt.Fprintf(buf, "%s} else {\n", indent)
		fmt.Fprintf(buf, "%s\t%s = nil\n", indent, dst)
		fmt.Fprintf(buf, "%s}\n", indent)
	default:
		panic(fmt.Sprintf("unhandled kind %T for %s", u, typeString(t)))
	}
}

// emitEqual writes statements that return false when a and b differ, recursing for
// nested refs and collecting struct-with-references types into g.eqHelpers.
func (g *gen) emitEqual(buf *bytes.Buffer, indent string, t ast.Expr, a, b string) {
	switch u := g.deref(t).(type) {
	case *ast.Ident, *ast.SelectorExpr:
		fmt.Fprintf(buf, "%sif %s != %s { return false }\n", indent, a, b)
	case *ast.ArrayType:
		if u.Len == nil {
			i := g.loopVar("i")
			fmt.Fprintf(buf, "%sif (%s == nil) != (%s == nil) { return false }\n", indent, a, b)
			fmt.Fprintf(buf, "%sif len(%s) != len(%s) { return false }\n", indent, a, b)
			fmt.Fprintf(buf, "%sfor %s := range %s {\n", indent, i, a)
			g.emitEqual(buf, indent+"\t", u.Elt, a+"["+i+"]", b+"["+i+"]")
			fmt.Fprintf(buf, "%s}\n", indent)
		} else if !g.holdsRefs(u.Elt) {
			fmt.Fprintf(buf, "%sif %s != %s { return false }\n", indent, a, b)
		} else {
			n, err := strconv.Atoi(u.Len.(*ast.BasicLit).Value)
			if err != nil {
				panic("array length: " + err.Error())
			}
			for i := 0; i < n; i++ {
				g.emitEqual(buf, indent, u.Elt, fmt.Sprintf("%s[%d]", a, i), fmt.Sprintf("%s[%d]", b, i))
			}
		}
	case *ast.StructType:
		if !g.holdsRefs(u) {
			fmt.Fprintf(buf, "%sif %s != %s { return false }\n", indent, a, b)
		} else {
			name := "snapEqual" + structName(t)
			if _, ok := g.eqHelpers[name]; !ok {
				g.eqHelpers[name] = &helper{name: name, typ: structName(t), strct: u, g: g}
			}
			fmt.Fprintf(buf, "%sif !%s(%s, %s) { return false }\n", indent, name, a, b)
		}
	case *ast.MapType:
		val := u.Value
		k, v := g.loopVar("k"), g.loopVar("v")
		fmt.Fprintf(buf, "%sif (%s == nil) != (%s == nil) { return false }\n", indent, a, b)
		fmt.Fprintf(buf, "%sif len(%s) != len(%s) { return false }\n", indent, a, b)
		fmt.Fprintf(buf, "%sfor %s, %s := range %s {\n", indent, k, v, a)
		if !g.holdsRefs(val) {
			fmt.Fprintf(buf, "%s\tif %s[%s] != %s { return false }\n", indent, b, k, v)
		} else {
			ov, ok := g.loopVar("ov"), g.loopVar("ok")
			fmt.Fprintf(buf, "%s\t%s, %s := %s[%s]\n", indent, ov, ok, b, k)
			fmt.Fprintf(buf, "%s\tif !%s { return false }\n", indent, ok)
			g.emitEqual(buf, indent+"\t", val, v, ov)
		}
		fmt.Fprintf(buf, "%s}\n", indent)
	case *ast.StarExpr:
		elem := u.X
		fmt.Fprintf(buf, "%sif (%s == nil) != (%s == nil) { return false }\n", indent, a, b)
		fmt.Fprintf(buf, "%sif %s != nil {\n", indent, a)
		if !g.holdsRefs(elem) {
			fmt.Fprintf(buf, "%s\tif *%s != *%s { return false }\n", indent, a, b)
		} else {
			g.emitEqual(buf, indent+"\t", elem, "*"+a, "*"+b)
		}
		fmt.Fprintf(buf, "%s}\n", indent)
	default:
		panic(fmt.Sprintf("unhandled kind %T for %s", u, typeString(t)))
	}
}

func (h *helper) emit(buf *bytes.Buffer) {
	fmt.Fprintf(buf, "\nfunc %s(src %s) %s {\n", h.name, h.typ, h.typ)
	fmt.Fprintf(buf, "\tvar dst %s\n\tdst = src\n", h.typ)
	structFields(h.strct, func(name string, typ ast.Expr) {
		h.g.emitCopy(buf, "\t", typ, "src."+name, "dst."+name)
	})
	fmt.Fprintf(buf, "\treturn dst\n}\n")
}

// emitEq writes a snapEqual<T>(a, b T) bool helper for a struct that holds references.
func (h *helper) emitEq(buf *bytes.Buffer) {
	fmt.Fprintf(buf, "\nfunc %s(a, b %s) bool {\n", h.name, h.typ)
	structFields(h.strct, func(name string, typ ast.Expr) {
		h.g.emitEqual(buf, "\t", typ, "a."+name, "b."+name)
	})
	fmt.Fprintf(buf, "\treturn true\n}\n")
}
