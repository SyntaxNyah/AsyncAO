// genclone emits internal/config/settings_clone.go: a generated deep copy of Settings
// that does `c := *s` then explicit deep copies of every map, slice, pointer and nested
// value that holds references. The reflection clone (settings.go cloneSettings) stays ONLY
// in the test as the oracle.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"go/types"
	"os"
	"sort"

	"golang.org/x/tools/go/packages"
)

var fset = token.NewFileSet()

func main() {
	cfg := &packages.Config{Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo, Tests: false, Fset: fset}
	pkgs, err := packages.Load(cfg, ".")
	if err != nil {
		panic(err)
	}
	pkg := pkgs[0]
	scope := pkg.Types.Scope()
	tn, ok := scope.Lookup("Settings").(*types.TypeName)
	if !ok {
		panic("Settings not found")
	}
	st := tn.Type().Underlying().(*types.Struct)
	self := pkg.Types.Path()

	qual := func(p *types.Package) string {
		if p == nil || p.Path() == self {
			return ""
		}
		return p.Name()
	}

	g := &gen{self: self, qual: qual, helpers: map[string]*helper{}, eqHelpers: map[string]*helper{}}

	var buf bytes.Buffer
	buf.WriteString("//go:generate go run ./genclone\n\n")
	buf.WriteString("// Code generated by genclone; DO NOT EDIT.\n")
	buf.WriteString("// settings_clone.go holds the generated deep copy of Settings: `c := *s` then\n")
	buf.WriteString("// explicit deep copies of every map, slice, pointer and nested value that holds\n")
	buf.WriteString("// references. The reflection clone (settings.go) stays ONLY as the test oracle;\n")
	buf.WriteString("// settings_clone_test.go pins this against it (DeepEqual + mutate-every-collection).\n\n")
	buf.WriteString("package config\n\n")
	buf.WriteString("// Clone returns a deep copy of s. Mutating the returned Settings (including its\n")
	buf.WriteString("// maps, slices and pointed-to values) never touches s.\n")
	buf.WriteString("func (s *Settings) Clone() *Settings {\n")
	buf.WriteString("\tif s == nil {\n\t\treturn nil\n\t}\n")
	buf.WriteString("\tc := *s\n")
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		if !f.Exported() {
			continue
		}
		g.emitCopy(&buf, "\t", f.Type(), "s."+f.Name(), "c."+f.Name())
	}
	buf.WriteString("\treturn &c\n}\n")

	buf.WriteString("\n// syncFromInline builds a fresh snapshot from the inline AssetPreferences data\n")
	buf.WriteString("// fields (the B0 bridge) with the same explicit deep copies as Clone. It replaces\n")
	buf.WriteString("// the reflection copyByNameDeep path.\n")
	buf.WriteString("func syncFromInline(p *AssetPreferences) *Settings {\n")
	buf.WriteString("\ts := &Settings{\n")
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		if !f.Exported() || holdsRefs(f.Type()) {
			continue
		}
		fmt.Fprintf(&buf, "\t\t%s: p.%s,\n", f.Name(), f.Name())
	}
	buf.WriteString("\t}\n")
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		if !f.Exported() || !holdsRefs(f.Type()) {
			continue
		}
		g.emitCopy(&buf, "\t", f.Type(), "p."+f.Name(), "s."+f.Name())
	}
	buf.WriteString("\treturn s\n}\n")

	buf.WriteString("\n// writeBackInline copies a normalized Settings snapshot back into the inline\n")
	buf.WriteString("// AssetPreferences data fields (the reverse of syncFromInline) so Save keeps\n")
	buf.WriteString("// marshalling the inline fields until the final flip.\n")
	buf.WriteString("func writeBackInline(s *Settings, p *AssetPreferences) {\n")
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		if !f.Exported() || holdsRefs(f.Type()) {
			continue
		}
		fmt.Fprintf(&buf, "\tp.%s = s.%s\n", f.Name(), f.Name())
	}
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		if !f.Exported() || !holdsRefs(f.Type()) {
			continue
		}
		g.emitCopy(&buf, "\t", f.Type(), "s."+f.Name(), "p."+f.Name())
	}
	buf.WriteString("}\n")

	buf.WriteString("\n// equal reports whether s and o hold identical values (deep, all fields, including\n")
	buf.WriteString("// every map, slice, pointer and nested value). It replaces the reflection\n")
	buf.WriteString("// changedFieldNames/valueChanged diff in Update.\n")
	buf.WriteString("func (s *Settings) equal(o *Settings) bool {\n")
	buf.WriteString("\tif s == o {\n\t\treturn true\n\t}\n")
	buf.WriteString("\tif s == nil || o == nil {\n\t\treturn false\n\t}\n")
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		if !f.Exported() {
			continue
		}
		g.emitEqual(&buf, "\t", f.Type(), "s."+f.Name(), "o."+f.Name())
	}
	buf.WriteString("\treturn true\n}\n")

	names := make([]string, 0, len(g.helpers))
	for n := range g.helpers {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		g.helpers[n].emit(&buf)
	}

	eqNames := make([]string, 0, len(g.eqHelpers))
	for n := range g.eqHelpers {
		eqNames = append(eqNames, n)
	}
	sort.Strings(eqNames)
	for _, n := range eqNames {
		g.eqHelpers[n].emitEq(&buf)
	}

	out, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, buf.String())
		panic(err)
	}
	if err := os.WriteFile("settings_clone.go", out, 0o644); err != nil {
		panic(err)
	}
	fmt.Println("wrote internal/config/settings_clone.go")
}

type helper struct {
	name  string
	typ   string
	strct *types.Struct
	g     *gen
}

type gen struct {
	self      string
	qual      types.Qualifier
	helpers   map[string]*helper
	eqHelpers map[string]*helper
	n         int // loop-variable uniquifier
}

// loopVar returns a fresh loop variable name for this generation.
func (g *gen) loopVar(prefix string) string {
	g.n++
	return fmt.Sprintf("%s%d", prefix, g.n)
}

// emitCopy writes statements that copy src into dst, recursing for nested refs and
// collecting struct-with-references types into g.helpers.
func (g *gen) emitCopy(buf *bytes.Buffer, indent string, t types.Type, src, dst string) {
	switch u := deref(t).(type) {
	case *types.Basic:
		// scalar: covered by c := *s
	case *types.Array:
		if holdsRefs(u.Elem()) {
			panic("array element holds references: " + types.TypeString(t, g.qual))
		}
	case *types.Struct:
		if !holdsRefs(u) {
			return // struct of scalars is a value copy
		}
		name := "snapClone" + structName(t)
		if _, ok := g.helpers[name]; !ok {
			g.helpers[name] = &helper{name: name, typ: structName(t), strct: u, g: g}
		}
		fmt.Fprintf(buf, "%s%s = %s(%s)\n", indent, dst, name, src)
	case *types.Slice:
		elem := u.Elem()
		if !holdsRefs(elem) {
			fmt.Fprintf(buf, "%sif %s != nil {\n", indent, src)
			fmt.Fprintf(buf, "%s\t%s = make(%s, len(%s))\n", indent, dst, types.TypeString(t, g.qual), src)
			fmt.Fprintf(buf, "%s\tcopy(%s, %s)\n", indent, dst, src)
			fmt.Fprintf(buf, "%s}\n", indent)
		} else {
			i := g.loopVar("i")
			fmt.Fprintf(buf, "%sif %s != nil {\n", indent, src)
			fmt.Fprintf(buf, "%s\t%s = make(%s, len(%s))\n", indent, dst, types.TypeString(t, g.qual), src)
			fmt.Fprintf(buf, "%s\tfor %s := range %s {\n", indent, i, src)
			g.emitCopy(buf, indent+"\t\t", elem, src+"["+i+"]", dst+"["+i+"]")
			fmt.Fprintf(buf, "%s\t}\n", indent)
			fmt.Fprintf(buf, "%s}\n", indent)
		}
	case *types.Map:
		val := u.Elem()
		k, v := g.loopVar("k"), g.loopVar("v")
		fmt.Fprintf(buf, "%sif %s != nil {\n", indent, src)
		fmt.Fprintf(buf, "%s\t%s = make(%s, len(%s))\n", indent, dst, types.TypeString(t, g.qual), src)
		fmt.Fprintf(buf, "%s\tfor %s, %s := range %s {\n", indent, k, v, src)
		if !holdsRefs(val) {
			fmt.Fprintf(buf, "%s\t\t%s[%s] = %s\n", indent, dst, k, v)
		} else {
			g.emitCopy(buf, indent+"\t\t", val, v, dst+"["+k+"]")
		}
		fmt.Fprintf(buf, "%s\t}\n", indent)
		fmt.Fprintf(buf, "%s}\n", indent)
	case *types.Pointer:
		elem := u.Elem()
		fmt.Fprintf(buf, "%sif %s != nil {\n", indent, src)
		if !holdsRefs(elem) {
			fmt.Fprintf(buf, "%s\tv := *%s\n\t%s\t%s = &v\n", indent, src, indent, dst)
		} else {
			fmt.Fprintf(buf, "%s\tvar v %s\n", indent, types.TypeString(elem, g.qual))
			g.emitCopy(buf, indent+"\t", elem, "*"+src, "v")
			fmt.Fprintf(buf, "%s\t%s = &v\n", indent, dst)
		}
		fmt.Fprintf(buf, "%s}\n", indent)
	default:
		panic(fmt.Sprintf("unhandled kind %T for %s", u, types.TypeString(t, g.qual)))
	}
}

// emitEqual writes statements that return false when a and b differ, recursing for nested
// refs and collecting struct-with-references types into g.eqHelpers.
func (g *gen) emitEqual(buf *bytes.Buffer, indent string, t types.Type, a, b string) {
	switch u := deref(t).(type) {
	case *types.Basic:
		fmt.Fprintf(buf, "%sif %s != %s { return false }\n", indent, a, b)
	case *types.Array:
		if !holdsRefs(u.Elem()) {
			fmt.Fprintf(buf, "%sif %s != %s { return false }\n", indent, a, b)
		} else {
			for i := 0; i < int(u.Len()); i++ {
				g.emitEqual(buf, indent, u.Elem(), fmt.Sprintf("%s[%d]", a, i), fmt.Sprintf("%s[%d]", b, i))
			}
		}
	case *types.Struct:
		if !holdsRefs(u) {
			fmt.Fprintf(buf, "%sif %s != %s { return false }\n", indent, a, b)
		} else {
			name := "snapEqual" + structName(t)
			if _, ok := g.eqHelpers[name]; !ok {
				g.eqHelpers[name] = &helper{name: name, typ: structName(t), strct: u, g: g}
			}
			fmt.Fprintf(buf, "%sif !%s(%s, %s) { return false }\n", indent, name, a, b)
		}
	case *types.Slice:
		elem := u.Elem()
		i := g.loopVar("i")
		fmt.Fprintf(buf, "%sif len(%s) != len(%s) { return false }\n", indent, a, b)
		fmt.Fprintf(buf, "%sfor %s := range %s {\n", indent, i, a)
		g.emitEqual(buf, indent+"\t", elem, a+"["+i+"]", b+"["+i+"]")
		fmt.Fprintf(buf, "%s}\n", indent)
	case *types.Map:
		val := u.Elem()
		k, v := g.loopVar("k"), g.loopVar("v")
		fmt.Fprintf(buf, "%sif len(%s) != len(%s) { return false }\n", indent, a, b)
		fmt.Fprintf(buf, "%sfor %s, %s := range %s {\n", indent, k, v, a)
		if !holdsRefs(val) {
			fmt.Fprintf(buf, "%s\tif %s[%s] != %s { return false }\n", indent, b, k, v)
		} else {
			ov, ok := g.loopVar("ov"), g.loopVar("ok")
			fmt.Fprintf(buf, "%s\t%s, %s := %s[%s]\n", indent, ov, ok, b, k)
			fmt.Fprintf(buf, "%s\tif !%s { return false }\n", indent, ok)
			g.emitEqual(buf, indent+"\t", val, v, ov)
		}
		fmt.Fprintf(buf, "%s}\n", indent)
	case *types.Pointer:
		elem := u.Elem()
		fmt.Fprintf(buf, "%sif (%s == nil) != (%s == nil) { return false }\n", indent, a, b)
		fmt.Fprintf(buf, "%sif %s != nil {\n", indent, a)
		if !holdsRefs(elem) {
			fmt.Fprintf(buf, "%s\tif *%s != *%s { return false }\n", indent, a, b)
		} else {
			g.emitEqual(buf, indent+"\t", elem, "*"+a, "*"+b)
		}
		fmt.Fprintf(buf, "%s}\n", indent)
	default:
		panic(fmt.Sprintf("unhandled kind %T for %s", u, types.TypeString(t, g.qual)))
	}
}

func (h *helper) emit(buf *bytes.Buffer) {
	fmt.Fprintf(buf, "\nfunc %s(src %s) %s {\n", h.name, h.typ, h.typ)
	fmt.Fprintf(buf, "\tvar dst %s\n\tdst = src\n", h.typ)
	for i := 0; i < h.strct.NumFields(); i++ {
		f := h.strct.Field(i)
		if !f.Exported() {
			continue
		}
		h.g.emitCopy(buf, "\t", f.Type(), "src."+f.Name(), "dst."+f.Name())
	}
	fmt.Fprintf(buf, "\treturn dst\n}\n")
}

// emitEq writes a snapEqual<T>(a, b T) bool helper for a struct that holds references.
func (h *helper) emitEq(buf *bytes.Buffer) {
	fmt.Fprintf(buf, "\nfunc %s(a, b %s) bool {\n", h.name, h.typ)
	for i := 0; i < h.strct.NumFields(); i++ {
		f := h.strct.Field(i)
		if !f.Exported() {
			continue
		}
		h.g.emitEqual(buf, "\t", f.Type(), "a."+f.Name(), "b."+f.Name())
	}
	fmt.Fprintf(buf, "\treturn true\n}\n")
}

func structName(t types.Type) string {
	if n, ok := t.(*types.Named); ok {
		return n.Obj().Name()
	}
	return ""
}

func deref(t types.Type) types.Type {
	if n, ok := t.(*types.Named); ok {
		return n.Underlying()
	}
	return t
}

// holdsRefs reports whether t (or anything inside it) holds a reference: a map, slice or
// pointer, directly or inside a struct or array.
func holdsRefs(t types.Type) bool {
	switch u := t.Underlying().(type) {
	case *types.Basic:
		return false
	case *types.Slice, *types.Map, *types.Pointer:
		return true
	case *types.Array:
		return holdsRefs(u.Elem())
	case *types.Struct:
		for i := 0; i < u.NumFields(); i++ {
			if u.Field(i).Exported() && holdsRefs(u.Field(i).Type()) {
				return true
			}
		}
		return false
	}
	return false
}

